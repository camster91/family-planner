export type BarcodeFoodFeedback = { key: BarcodeFoodMessage; params?: Record<string, string | number> };
export function barcodeFeedback(key: BarcodeFoodMessage, params?: Record<string, string | number>): BarcodeFoodFeedback {
  return { key, ...(params ? { params } : {}) };
}
const messages = { en, es };
export function useBarcodeFoodText() {
  const { t, locale } = useTranslation();
  return useCallback((key: BarcodeFoodMessage, params?: Record<string, string | number>) =>
    t(key, params ? Object.fromEntries(Object.entries(params).map(([name, value]) =>
      [name, typeof value === "number" ? new Intl.NumberFormat(locale).format(value) : value])) : undefined, messages), [t, locale]);
}
