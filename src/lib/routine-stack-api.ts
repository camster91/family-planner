const activeSeriesFrequencies = new Set(["daily", "weekly", "monthly"]);

function candidateAnchorIsValid(anchor: {
  id: string;
  family_id: string;
  recurrence_id: string | null;
  is_template: boolean;
  frequency: string;
}): boolean {
  const self = anchor.recurrence_id === anchor.id;
  const active =
    anchor.is_template && activeSeriesFrequencies.has(anchor.frequency);
  const stopped = !anchor.is_template && anchor.frequency === "once";
  return self && (active || stopped);
}

function identityRefsByUser(
  refs: readonly CandidateIdentityRef[],
  familyId: string,
  members: ReadonlyMap<string, CandidateMember>,
) {
  const byUser = new Map<string, Set<string>>();
  const blocked = new Set<string>();
  for (const ref of refs) {
    const existing = byUser.get(ref.user_id) ?? new Set<string>();
    existing.add(ref.member_id);
    byUser.set(ref.user_id, existing);
    const member = members.get(ref.member_id);
    if (ref.family_id !== familyId || !member) blocked.add(ref.user_id);
    if (member && (member.archived_at || member.erasure_user_id)) {
      blocked.add(ref.user_id);
    }
  }
  for (const [userId, memberIds] of byUser) {
    if (memberIds.size !== 1) blocked.add(userId);
  }
  return { byUser, blocked };
}

/**
 * Read the bounded parent-only catalog used to start or extend a routine.
 * Account IDs are returned from the User table; member IDs are only echoed
 * from existing chore rows and are never inferred from names or accounts.
 */
export async function readParentRoutineStackCandidates(
  db: RoutineStackCandidateDb,
  actor: ParentRoutineStackActor,
  occurrenceDate: string,
  page: RoutineStackCandidatePage = {},
): Promise<ParentRoutineStackCandidates | null> {
  if (actor.role !== "parent") return null;
  const bounds = occurrenceBounds(occurrenceDate);
  if (!bounds) return null;
  const limit = page.limit ?? CHORE_PAGE_MAX;
  if (!Number.isInteger(limit) || limit < 1 || limit > CHORE_PAGE_MAX) {
    return null;
  }

  const users = (await db.user.findMany({
    where: { family_id: actor.familyId },
    select: { id: true, name: true, role: true },
    orderBy: { name: "asc" },
  })) as CandidateAccount[];
  const userIds = users.map((user) => user.id);
  const [members, legacyMappings, accountLinks, rows] = await Promise.all([
    db.householdMember.findMany({
      where: { family_id: actor.familyId },
      select: { id: true, archived_at: true, erasure_user_id: true },
    }),
    userIds.length
      ? db.householdMemberLegacyMapping.findMany({
          where: { user_id: { in: userIds } },
          select: { user_id: true, member_id: true, family_id: true },
        })
      : Promise.resolve([]),
    userIds.length
      ? db.householdMemberAccountLink.findMany({
          where: { user_id: { in: userIds } },
          select: { user_id: true, member_id: true, family_id: true },
        })
      : Promise.resolve([]),
    db.chore.findMany({
      where: {
        family_id: actor.familyId,
        routine_stack_id: null,
        is_template: false,
        due_date: { gte: bounds.start, lt: bounds.end },
        ...(page.cursor ? { AND: [afterChoreCursor(page.cursor, "asc")] } : {}),
      },
      select: ROUTINE_STACK_CANDIDATE_SELECT,
      orderBy: choreOrderBy("asc"),
      take: limit + 1,
    }),
  ]);

  const memberMap = new Map(
    (members as CandidateMember[]).map((member) => [member.id, member]),
  );
  const refs = [
    ...(legacyMappings as CandidateIdentityRef[]),
    ...(accountLinks as CandidateIdentityRef[]),
  ];
  const { byUser, blocked } = identityRefsByUser(
    refs,
    actor.familyId,
    memberMap,
  );
  const eligibleAccounts = users.filter((user) => !blocked.has(user.id));
  const eligibleAccountIds = new Set(eligibleAccounts.map((user) => user.id));
  const eligibleMemberIds = new Set(
    [...memberMap.values()]
      .filter((member) => !member.archived_at && !member.erasure_user_id)
      .map((member) => member.id),
  );
  const rawRows = rows as CandidateChore[];
  const pageRows = rawRows.slice(0, limit);
  const recurrenceIds = [
    ...new Set(
      pageRows.flatMap((row) =>
        typeof row.recurrence_id === "string" ? [row.recurrence_id] : [],
      ),
    ),
  ];
  const anchors = recurrenceIds.length
    ? ((await db.chore.findMany({
        where: { family_id: actor.familyId, id: { in: recurrenceIds } },
        select: {
          id: true,
          family_id: true,
          recurrence_id: true,
          is_template: true,
          frequency: true,
        },
      })) as Array<{
        id: string;
        family_id: string;
        recurrence_id: string | null;
        is_template: boolean;
        frequency: string;
      }>)
    : [];
  const validAnchors = new Set(
    anchors.filter(candidateAnchorIsValid).map((anchor) => anchor.id),
  );
  const candidates = pageRows
    .filter((row) => {
      if (row.is_template || row.routine_stack_id || row.member_subject_erased)
        return false;
      if (!eligibleAccountIds.has(row.assigned_to)) return false;
      if (
        row.assigned_member_id !== null &&
        (!eligibleMemberIds.has(row.assigned_member_id) ||
          byUser.get(row.assigned_to)?.size !== 1 ||
          !byUser.get(row.assigned_to)?.has(row.assigned_member_id))
      ) {
        return false;
      }
      if (typeof row.recurrence_id === "string") {
        if (!row.recurrence_id || !validAnchors.has(row.recurrence_id))
          return false;
      }
      return true;
    })
    .map((row) => ({
      id: row.id,
      title: row.title,
      description: row.description,
      assigned_to: row.assigned_to,
      assigned_member_id: row.assigned_member_id,
      due_date: row.due_date.toISOString(),
      recurrence_id: row.recurrence_id,
      is_template: false as const,
      routine: row.routine,
      routine_order: row.routine_order,
      status: row.status,
      frequency: row.frequency,
      weekly_days: row.weekly_days,
      difficulty: row.difficulty,
      icon: row.icon,
      expected_fingerprint: fingerprintRoutineStackSelectedStep({
        id: row.id,
        family_id: actor.familyId,
        assigned_to: row.assigned_to,
        assigned_member_id: row.assigned_member_id,
        member_subject_erased: row.member_subject_erased,
        due_date: row.due_date,
        recurrence_id: row.recurrence_id,
        is_template: row.is_template,
        routine: row.routine,
        routine_order: row.routine_order,
      }),
    }));
  const hasMore = rawRows.length > limit;
  const nextCursor = hasMore
    ? encodeChoreCursor(pageRows[pageRows.length - 1])
    : null;

  return {
    occurrence_date: occurrenceDate,
    candidates,
    assignmentOptions: eligibleAccounts.map((user) => ({
      accountId: user.id,
      name: user.name,
      role: user.role,
    })),
    hasMore,
    nextCursor,
  };
}

/** Read one dated stack for the parent editor; all resource predicates include family_id. */
export async function readParentRoutineStack(
  db: RoutineStackReadDb,
  actor: ParentRoutineStackActor,
  stackId: string,
  occurrenceDate: string,
): Promise<ParentRoutineStackRead | null> {
  // Keep the helper safe when called outside the route. The route authenticates
  // first, but a future server caller must not accidentally turn this broad
  // parent projection into a child/teen read model.
  if (actor.role !== "parent") return null;
  const bounds = occurrenceBounds(occurrenceDate);
  if (!bounds) return null;

  const stack = await db.routineStack.findFirst({
    where: { id: stackId, family_id: actor.familyId },
    select: { id: true, family_id: true, label: true, version: true },
  });
  if (!stack) return null;

  const [steps, members] = await Promise.all([
    db.chore.findMany({
      where: {
        family_id: actor.familyId,
        routine_stack_id: stack.id,
        due_date: { gte: bounds.start, lt: bounds.end },
      },
      select: ROUTINE_STACK_STEP_SELECT,
      orderBy: { routine_order: "asc" },
    }),
    db.householdMember.findMany({
      where: { family_id: actor.familyId },
      select: {
        id: true,
        name: true,
        role: true,
        archived_at: true,
        erasure_user_id: true,
        legacy_mapping: { select: { user_id: true } },
        account_link: { select: { user_id: true } },
      },
      orderBy: { name: "asc" },
    }),
  ]);

  const snapshot = fingerprintRoutineStackSnapshot(
    steps as unknown as readonly RoutineStackSnapshotStep[],
  );
  const memberProjection = members.map(({ id, role }) => ({ id, role }));
  const compact = projectRoutineStackResponse({
    stack_id: stack.id,
    version: stack.version,
    fingerprint: snapshot,
    steps: steps.map((step) => ({
      id: step.id,
      assigned_to: step.assigned_to,
      assigned_member_id: step.assigned_member_id,
    })),
    members: memberProjection,
  });

  return {
    stack,
    occurrence_date: occurrenceDate,
    fingerprint: snapshot,
    steps: steps.map(parentStep),
    members: members.map((member) => ({
      id: member.id,
      displayName: member.name,
      role: member.role,
      subjectState: memberSubjectState(member),
    })),
    compact,
  };
}

function mutationError(
  status: number,
  code: string,
  message: string,
  retryable = false,
): RoutineStackMutationResult {
  return {
    status,
    body: {
      error: { code, message, ...(retryable ? { retryable: true } : {}) },
    },
  };
}

/**
 * Create/read the stack receipt and run the core coordinator in one transaction.
 * The user lock serializes same-user keys before the unique receipt lookup, so
 * concurrent duplicates replay deterministically without generic post-effect
 * idempotency takeover.
 */
export async function saveParentRoutineStack(
  db: RoutineStackWriteDb,
  input: unknown,
  actor: ParentRoutineStackActor,
  key: string,
  now = new Date(),
): Promise<RoutineStackMutationResult> {
  const draft = normalizeRoutineStackDraft(input);
  const requestHash = hashIdempotentRequest(ROUTINE_STACK_ACTION, draft);
  const scope = `user:${actor.userId}`;

  return db.$transaction(async (tx) => {
    await lockUser(tx, actor.userId);
    await lockHousehold(tx, actor.familyId);

    const currentActor = await tx.user.findUnique({
      where: { id: actor.userId },
      select: { family_id: true, role: true },
    });
    if (
      !currentActor ||
      currentActor.family_id !== actor.familyId ||
      currentActor.role !== "parent"
    ) {
      return mutationError(403, "FORBIDDEN", "Parent access is required.");
    }

    let receipt = await tx.idempotencyRecord.findUnique({
      where: { scope_key: { scope, key } },
      select: {
        id: true,
        family_id: true,
        user_id: true,
        action: true,
        request_hash: true,
        response_status: true,
        response_body: true,
        expires_at: true,
      },
    });
    if (receipt && receipt.expires_at <= now) {
      await tx.idempotencyRecord.delete({ where: { id: receipt.id } });
      receipt = null;
    }
    if (receipt) {
      if (
        receipt.family_id !== actor.familyId ||
        receipt.user_id !== actor.userId ||
        receipt.action !== ROUTINE_STACK_ACTION ||
        receipt.request_hash !== requestHash
      ) {
        return mutationError(
          422,
          "IDEMPOTENCY_KEY_REUSED",
          "This retry contains different routine data.",
        );
      }
      if (receipt.response_status === null) {
        return mutationError(
          409,
          "IDEMPOTENCY_IN_PROGRESS",
          "Please retry this routine.",
          true,
        );
      }
    } else {
      receipt = await tx.idempotencyRecord.create({
        data: {
          scope,
          key,
          family_id: actor.familyId,
          user_id: actor.userId,
          action: ROUTINE_STACK_ACTION,
          request_hash: requestHash,
          response_status: null,
          created_at: now,
          expires_at: new Date(now.getTime() + IDEMPOTENCY_TTL_MS),
        },
        select: {
          id: true,
          family_id: true,
          user_id: true,
          action: true,
          request_hash: true,
          response_status: true,
          response_body: true,
          expires_at: true,
        },
      });
    }

    const memberDictionary = await tx.householdMember.findMany({
      where: { family_id: actor.familyId },
      select: { id: true, role: true },
    });
    return mutateRoutineStackInTx(tx as object, draft, actor, {
      recordId: receipt.id,
      memberDictionary,
    });
  });
}
