function occurrenceBounds(value: string): { start: Date; end: Date } | null {
  const start = parseDateOnly(value);
  if (!start) return null;
  const end = new Date(start);
  end.setUTCDate(end.getUTCDate() + 1);
  return { start, end };
}

function memberSubjectState(member: {
  archived_at: Date | null;
  erasure_user_id: string | null;
  legacy_mapping?: { user_id: string } | null;
  account_link?: { user_id: string } | null;
}): "eligible" | "archived" | "erased" | "dormant" {
  if (member.erasure_user_id) return "erased";
  if (member.archived_at) return "archived";
  if (!member.legacy_mapping && !member.account_link) return "dormant";
  return "eligible";
}

