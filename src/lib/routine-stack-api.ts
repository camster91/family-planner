/**
 * Keep this boundary structural.  The routine-stack migration is additive and
 * the shared generated client is intentionally regenerated by the release
 * owner in an isolated output.  Route tests and older checkouts can therefore
 * type-check without pretending that the pre-migration client has these
 * delegates/fields.
 */
export type RoutineStackReadDb = {
  routineStack: { findFirst(args: object): Promise<any> };
  chore: { findMany(args: object): Promise<any[]> };
  householdMember: { findMany(args: object): Promise<any[]> };
};

export type RoutineStackWriteDb = {
  $transaction<T>(callback: (tx: any) => Promise<T>): Promise<T>;
};

type ParentStep = {
  id: string;
  family_id: string;
  title: string;
  description: string | null;
  assigned_to: string;
  assigned_member_id: string | null;
  member_subject_erased: boolean;
  due_date: Date;
  recurrence_id: string | null;
  is_template: boolean;
  routine: string | null;
  routine_order: number | null;
  status: string;
  frequency: string;
  weekly_days: number[];
  difficulty: string | null;
  icon: string | null;
  points: number;
  photo_url: string | null;
  photo_verified: boolean;
  verified_at: Date | null;
  verified_notes: string | null;
  completed_at: Date | null;
};

function occurrenceBounds(value: string): { start: Date; end: Date } | null {
  const start = parseDateOnly(value);
  if (!start) return null;
  const end = new Date(start);
  end.setUTCDate(end.getUTCDate() + 1);
  return { start, end };
}

function memberSubjectState(member: {
  archived_at: Date | null;
  erasure_user_id: string | null;
  legacy_mapping?: { user_id: string } | null;
  account_link?: { user_id: string } | null;
}): "eligible" | "archived" | "erased" | "dormant" {
  if (member.erasure_user_id) return "erased";
  if (member.archived_at) return "archived";
  if (!member.legacy_mapping && !member.account_link) return "dormant";
  return "eligible";
}

function parentStep(step: ParentStep) {
  return {
    id: step.id,
    title: step.title,
    description: step.description,
    assigned_to: step.assigned_to,
    assigned_member_id: step.assigned_member_id,
    member_subject_erased: step.member_subject_erased,
    due_date: step.due_date.toISOString(),
    recurrence_id: step.recurrence_id,
    is_template: step.is_template,
    routine: step.routine,
    routine_order: step.routine_order,
    status: step.status,
    frequency: step.frequency,
    weekly_days: step.weekly_days,
    difficulty: step.difficulty,
    icon: step.icon,
    points: step.points,
    photo_url: step.photo_url,
    photo_verified: step.photo_verified,
    verified_at: step.verified_at?.toISOString() ?? null,
    verified_notes: step.verified_notes,
    completed_at: step.completed_at?.toISOString() ?? null,
  };
}

export type ParentRoutineStackRead = {
  stack: {
    id: string;
    family_id: string;
    label: string;
    version: number;
  };
  occurrence_date: string;
  fingerprint: string;
  steps: ReturnType<typeof parentStep>[];
  members: {
    id: string;
    displayName: string;
    role: string;
    subjectState: "eligible" | "archived" | "erased" | "dormant";
  }[];
  compact: ReturnType<typeof projectRoutineStackResponse>;
};

/** Read one dated stack for the parent editor; all resource predicates include family_id. */
export async function readParentRoutineStack(
  db: RoutineStackReadDb,
  actor: ParentRoutineStackActor,
  stackId: string,
  occurrenceDate: string,
): Promise<ParentRoutineStackRead | null> {
  // Keep the helper safe when called outside the route. The route authenticates
  // first, but a future server caller must not accidentally turn this broad
  // parent projection into a child/teen read model.
  if (actor.role !== "parent") return null;
  const bounds = occurrenceBounds(occurrenceDate);
  if (!bounds) return null;

  const stack = await db.routineStack.findFirst({
    where: { id: stackId, family_id: actor.familyId },
    select: { id: true, family_id: true, label: true, version: true },
  });
  if (!stack) return null;

  const [steps, members] = await Promise.all([
    db.chore.findMany({
      where: {
        family_id: actor.familyId,
        routine_stack_id: stack.id,
        due_date: { gte: bounds.start, lt: bounds.end },
      },
      select: ROUTINE_STACK_STEP_SELECT,
      orderBy: { routine_order: "asc" },
    }),
    db.householdMember.findMany({
      where: { family_id: actor.familyId },
      select: {
        id: true,
        name: true,
        role: true,
        archived_at: true,
        erasure_user_id: true,
        legacy_mapping: { select: { user_id: true } },
        account_link: { select: { user_id: true } },
      },
      orderBy: { name: "asc" },
    }),
  ]);

  const snapshot = fingerprintRoutineStackSnapshot(
    steps as unknown as readonly RoutineStackSnapshotStep[],
  );
  const memberProjection = members.map(({ id, role }) => ({ id, role }));
  const compact = projectRoutineStackResponse({
    stack_id: stack.id,
    version: stack.version,
    fingerprint: snapshot,
    steps: steps.map((step) => ({
      id: step.id,
      assigned_to: step.assigned_to,
      assigned_member_id: step.assigned_member_id,
    })),
    members: memberProjection,
  });

  return {
    stack,
    occurrence_date: occurrenceDate,
    fingerprint: snapshot,
    steps: steps.map(parentStep),
    members: members.map((member) => ({
      id: member.id,
      displayName: member.name,
      role: member.role,
      subjectState: memberSubjectState(member),
    })),
    compact,
  };
}

function mutationError(
  status: number,
  code: string,
  message: string,
  retryable = false,
): RoutineStackMutationResult {
  return {
    status,
    body: {
      error: { code, message, ...(retryable ? { retryable: true } : {}) },
    },
  };
}

/**
 * Create/read the stack receipt and run the core coordinator in one transaction.
 * The user lock serializes same-user keys before the unique receipt lookup, so
 * concurrent duplicates replay deterministically without generic post-effect
 * idempotency takeover.
 */
export async function saveParentRoutineStack(
  db: RoutineStackWriteDb,
  input: unknown,
  actor: ParentRoutineStackActor,
  key: string,
  now = new Date(),
): Promise<RoutineStackMutationResult> {
  const draft = normalizeRoutineStackDraft(input);
  const requestHash = hashIdempotentRequest(ROUTINE_STACK_ACTION, draft);
  const scope = `user:${actor.userId}`;

  return db.$transaction(async (tx) => {
    await lockUser(tx, actor.userId);
    await lockHousehold(tx, actor.familyId);

    const currentActor = await tx.user.findUnique({
      where: { id: actor.userId },
      select: { family_id: true, role: true },
    });
    if (
      !currentActor ||
      currentActor.family_id !== actor.familyId ||
      currentActor.role !== "parent"
    ) {
      return mutationError(403, "FORBIDDEN", "Parent access is required.");
    }

    let receipt = await tx.idempotencyRecord.findUnique({
      where: { scope_key: { scope, key } },
      select: {
        id: true,
        family_id: true,
        user_id: true,
        action: true,
        request_hash: true,
        response_status: true,
        response_body: true,
        expires_at: true,
      },
    });
    if (receipt && receipt.expires_at <= now) {
      await tx.idempotencyRecord.delete({ where: { id: receipt.id } });
      receipt = null;
    }
    if (receipt) {
      if (
        receipt.family_id !== actor.familyId ||
        receipt.user_id !== actor.userId ||
        receipt.action !== ROUTINE_STACK_ACTION ||
        receipt.request_hash !== requestHash
      ) {
        return mutationError(
          422,
          "IDEMPOTENCY_KEY_REUSED",
          "This retry contains different routine data.",
        );
      }
      if (receipt.response_status === null) {
        return mutationError(
          409,
          "IDEMPOTENCY_IN_PROGRESS",
          "Please retry this routine.",
          true,
        );
      }
    } else {
      receipt = await tx.idempotencyRecord.create({
        data: {
          scope,
          key,
          family_id: actor.familyId,
          user_id: actor.userId,
          action: ROUTINE_STACK_ACTION,
          request_hash: requestHash,
          response_status: null,
          created_at: now,
          expires_at: new Date(now.getTime() + IDEMPOTENCY_TTL_MS),
        },
        select: {
          id: true,
          family_id: true,
          user_id: true,
          action: true,
          request_hash: true,
          response_status: true,
          response_body: true,
          expires_at: true,
        },
      });
    }

    const memberDictionary = await tx.householdMember.findMany({
      where: { family_id: actor.familyId },
      select: { id: true, role: true },
    });
    return mutateRoutineStackInTx(tx as object, draft, actor, {
      recordId: receipt.id,
      memberDictionary,
    });
  });
}
