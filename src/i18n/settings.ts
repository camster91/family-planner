export const settingsMessages = { en: settingsEnglish, es: settingsSpanish };
export type SettingsFeedback =
  | { key: SettingsMessage; params?: Record<string, string | number> }
  | { raw: string };
export function settingsFeedback(
  key: SettingsMessage,
  params?: Record<string, string | number>,
): SettingsFeedback {
  return { key, ...(params ? { params } : {}) };
}
/** Single interpolation pass; private parameters are never interpreted as templates. */
export function settingsFeedbackEnglish(feedback: SettingsFeedback): string {
  if ("raw" in feedback) return feedback.raw;
  return settingsEnglish[feedback.key].replace(
    /\{(\w+)\}/g,
    (all, key: string) =>
      Object.prototype.hasOwnProperty.call(feedback.params ?? {}, key)
        ? String(feedback.params![key])
        : all,
  );
}
/** Tagged owned fallback keeps network/provider errors raw, including text equal to a local label. */
export class SettingsFeedbackError extends Error {
  constructor(readonly feedback: SettingsFeedback) {
    super(settingsFeedbackEnglish(feedback));
  }
}
export function settingsError(
  error: unknown,
  fallback: SettingsMessage,
): SettingsFeedback {
  return error instanceof SettingsFeedbackError
    ? error.feedback
    : error instanceof Error
      ? { raw: error.message }
      : settingsFeedback(fallback);
}
export function settingsResponseError(
  raw: unknown,
  fallback: SettingsMessage,
): SettingsFeedback {
  return raw ? { raw: String(raw) } : settingsFeedback(fallback);
}
